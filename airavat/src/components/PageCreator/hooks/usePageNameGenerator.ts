import { useState, useCallback, useEffect } from 'react';

interface UsePageNameGeneratorReturn {
  name: string;
  setName: (name: string) => void;
  isManualEdit: boolean;
  setIsManualEdit: (value: boolean) => void;
  generatePageName: (title: string) => string;
  syncNameWithTitle: (title: string) => void;
  handleNameChange: (newName: string, title: string) => void;
  reset: () => void;
}

/**
 * Generates a URL-friendly page name from a title
 */
export function generatePageName(title: string): string {
  if (!title.trim()) return '';

  return title
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .substring(0, 60);
}

/**
 * Hook for managing page name generation and manual editing
 */
export function usePageNameGenerator(): UsePageNameGeneratorReturn {
  const [name, setName] = useState<string>('');
  const [isManualEdit, setIsManualEdit] = useState(false);

  const syncNameWithTitle = useCallback((title: string) => {
    if (!isManualEdit) {
      const generatedName = generatePageName(title);
      setName(generatedName);
    }
  }, [isManualEdit]);

  const handleNameChange = useCallback((newName: string, title: string) => {
    setName(newName);

    const autoGeneratedName = generatePageName(title);
    if (!isManualEdit && newName !== autoGeneratedName) {
      setIsManualEdit(true);
    }

    if (isManualEdit && !newName.trim() && title.trim()) {
      setIsManualEdit(false);
      setName(generatePageName(title));
    }
  }, [isManualEdit]);

  const reset = useCallback(() => {
    setName('');
    setIsManualEdit(false);
  }, []);

  // Auto-sync when title changes (if not manually edited)
  useEffect(() => {
    // This effect is triggered by parent component
  }, []);

  return {
    name,
    setName,
    isManualEdit,
    setIsManualEdit,
    generatePageName,
    syncNameWithTitle,
    handleNameChange,
    reset,
  };
}
